class BitmapFont:
    """Native bitmap font renderer — no Pillow needed for text."""

    def __init__(self, font_data=None, width=5, height=8):
        """
        Args:
            font_data: dict mapping char to list of row bytes
            width: glyph width in pixels
            height: glyph height in pixels (rows per glyph)
        """
        self.data = font_data or FONT_5x8
        self.w = width
        self.h = height
        self.spacing = 1  # 1px between characters

    def text_width(self, text):
        """Return the pixel width of *text* rendered in this font."""
        n = len(text)
        if n == 0:
            return 0
        return n * self.w + (n - 1) * self.spacing

    def draw(self, d, x, y, text, fill=255):
        """Blit *text* onto a Pillow ImageDraw at pixel position (x, y).

        Falls back to '?' for unknown glyphs.
        """
        cursor = x
        for ch in text:
            glyph = self.data.get(ch, self.data.get('?', self.data.get(' ')))
            if glyph is None:
                cursor += self.w + self.spacing
                continue
            for row_idx, row_byte in enumerate(glyph):
                py = y + row_idx
                if py < 0 or py >= H:
                    continue
                for bit in range(self.w):
                    if row_byte & (1 << (self.w - 1 - bit)):
                        px = cursor + bit
                        if 0 <= px < W:
                            d.point((px, py), fill=fill)
            cursor += self.w + self.spacing

    def draw_icon(self, d, x, y, name, fill=255):
        """Blit a named icon glyph at (x, y)."""
        glyph = ICON_GLYPHS.get(name)
        if glyph is None:
            return
        cursor = x
        for row_idx, row_byte in enumerate(glyph):
            py = y + row_idx
            if py < 0 or py >= H:
                continue
            for bit in range(self.w):
                if row_byte & (1 << (self.w - 1 - bit)):
                    px = cursor + bit
                    if 0 <= px < W:
                        d.point((px, py), fill=fill)


