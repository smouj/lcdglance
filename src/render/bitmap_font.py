"""Native bitmap font for the G510 160×43 mono LCD.

Renders text directly to the frame buffer without Pillow — each glyph
is a pre-designed byte array that blits in O(n) with zero binarisation
artefacts. At 5×7 pixels, every character is crisp and legible on the
real hardware. A 3×5 micro font is available for labels and icons.

Design criteria:
  - 5×7 body font: all printable ASCII, descenders to row 8
  - 3×5 micro font: labels, arrows, single digits
  - No anti-aliasing: each pixel is on or off, no thresholds needed
  - Direct byte blit: no Pillow, no LUT, no convert, no dithering

The font data is stored as flat byte arrays, one byte per row, MSB left.
For a 5-wide glyph at position (x, y), row r sets pixels at
  x+0..x+4 from (glyph[r] >> (4-bit)) & 1 for bit in range(5).
"""
